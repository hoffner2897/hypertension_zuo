enum ExerciseRecommendationEngine {
    /// UI-friendly adapter for the strings currently stored by ActionGenerateDemoView.
    static func recommendations(
        sceneTitle: String,
        energyTitle: String,
        contextTitles: Set<String>,
        limit: Int = 4
    ) -> [LowBarrierExercise] {
        guard let scene = ExerciseScene(title: sceneTitle),
              let energy = ExerciseEnergyTier(title: energyTitle) else {
            return []
        }

        let contexts = Set(contextTitles.compactMap(ExerciseContext.init(rawValue:)))
        return recommendations(scene: scene, energy: energy, contexts: contexts, limit: limit)
    }

    static func recommendations(
        scene: ExerciseScene,
        energy: ExerciseEnergyTier,
        contexts: Set<ExerciseContext>,
        limit: Int = 4
    ) -> [LowBarrierExercise] {
        rankedRecommendations(
            scene: scene,
            energy: energy,
            contexts: contexts,
            limit: limit
        ).map(\.exercise)
    }

    static func rankedRecommendations(
        scene: ExerciseScene,
        energy: ExerciseEnergyTier,
        contexts: Set<ExerciseContext>,
        limit: Int = 4
    ) -> [ExerciseRecommendation] {
        let candidates = LowBarrierExerciseCatalog.exercises(in: scene)
        let boundedLimit = max(0, min(limit, candidates.count))
        guard boundedLimit > 0 else { return [] }

        let scored = candidates.map { exercise -> ExerciseRecommendation in
            let energyScore = self.energyScore(selected: energy, exercise: exercise.energyTier)
            let contextScore = contexts.reduce(into: 0) { total, context in
                total += exercise.contextScores[context]
            }
            return ExerciseRecommendation(
                exercise: exercise,
                score: energyScore + contextScore,
                energyScore: energyScore,
                contextScore: contextScore
            )
        }
        .sorted { lhs, rhs in
            stableHigherScore(lhs, rhs)
        }

        var selected: [ExerciseRecommendation] = []
        for candidate in scored {
            if candidate.exercise.type == .isometric,
               selected.contains(where: { $0.exercise.type == .isometric }) {
                continue
            }
            selected.append(candidate)
            if selected.count == boundedLimit { break }
        }

        ensureCategoryBalance(
            selected: &selected,
            rankedCandidates: scored,
            catalog: candidates,
            limit: boundedLimit
        )

        return selected.sorted { lhs, rhs in
            stableHigherScore(lhs, rhs)
        }
    }

    private static func energyScore(
        selected: ExerciseEnergyTier,
        exercise: ExerciseEnergyTier
    ) -> Int {
        switch abs(selected.rawValue - exercise.rawValue) {
        case 0: return 4
        case 1: return 2
        default: return 0
        }
    }

    private static func stableHigherScore(
        _ lhs: ExerciseRecommendation,
        _ rhs: ExerciseRecommendation
    ) -> Bool {
        if lhs.score != rhs.score { return lhs.score > rhs.score }
        return lhs.exercise.catalogOrder < rhs.exercise.catalogOrder
    }

    private static func ensureCategoryBalance(
        selected: inout [ExerciseRecommendation],
        rankedCandidates: [ExerciseRecommendation],
        catalog: [LowBarrierExercise],
        limit: Int
    ) {
        guard limit >= 2,
              catalog.contains(where: { $0.type.isAerobic }),
              catalog.contains(where: { !$0.type.isAerobic }) else {
            return
        }

        let hasAerobic = selected.contains { $0.exercise.type.isAerobic }
        let hasNonAerobic = selected.contains { !$0.exercise.type.isAerobic }
        guard !hasAerobic || !hasNonAerobic else { return }

        let needsAerobic = !hasAerobic
        guard let replacement = rankedCandidates.first(where: { candidate in
            candidate.exercise.type.isAerobic == needsAerobic &&
                !selected.contains(where: { $0.id == candidate.id }) &&
                (candidate.exercise.type != .isometric ||
                    !selected.contains(where: { $0.exercise.type == .isometric }))
        }) else { return }

        let replaceableIndices = selected.indices.filter { index in
            selected[index].exercise.type.isAerobic != needsAerobic
        }
        guard let index = replaceableIndices.max(by: { lhs, rhs in
            stableHigherScore(selected[lhs], selected[rhs])
        }) else { return }

        selected[index] = replacement
    }
}
