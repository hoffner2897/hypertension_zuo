import Foundation

/// The four locations supported by the low-barrier exercise catalog.
enum ExerciseScene: String, CaseIterable, Codable, Sendable {
    case privateIndoor = "私人室内"
    case publicIndoor = "公共室内"
    case publicOutdoor = "公共室外"
    case privateOrOpenOutdoor = "私人/开放室外"

    init?(title: String) {
        let normalized = title
            .trimmingCharacters(in: .whitespacesAndNewlines)
            .replacingOccurrences(of: "／", with: "/")
        self.init(rawValue: normalized)
    }

    /// Preserves the wording used by the source workbook when an audit label is needed.
    var sourceTitle: String {
        switch self {
        case .privateOrOpenOutdoor:
            return "私人／开放室外"
        default:
            return rawValue
        }
    }
}

enum ExerciseType: String, Codable, Sendable {
    case aerobic = "有氧运动"
    case dynamicResistance = "动态抗阻运动"
    case isometric = "等长运动"

    var isAerobic: Bool { self == .aerobic }
}

enum ExerciseEnergyTier: Int, CaseIterable, Codable, Sendable {
    case low = 1
    case medium = 2
    case high = 3

    init?(title: String) {
        switch title.trimmingCharacters(in: .whitespacesAndNewlines) {
        case "精力低": self = .low
        case "精力一般": self = .medium
        case "精力较好": self = .high
        default: return nil
        }
    }

    var title: String {
        switch self {
        case .low: return "精力低"
        case .medium: return "精力一般"
        case .high: return "精力较好"
        }
    }
}

enum ExerciseContext: String, CaseIterable, Codable, Hashable, Sendable {
    case afterMeal = "饭后"
    case afterSitting = "久坐后"
    case afterStress = "压力后"
    case sleepDeprived = "睡眠不足"
    case afterActivity = "刚活动后"
    case noSpecialCondition = "无特殊情况"
}

/// Every catalog item explicitly declares its score for each selectable context.
/// Valid scored values are +3, +1, -1 and -3. "无特殊情况" always contributes 0.
struct ExerciseContextScores: Equatable, Sendable {
    let afterMeal: Int
    let afterSitting: Int
    let afterStress: Int
    let sleepDeprived: Int
    let afterActivity: Int

    subscript(context: ExerciseContext) -> Int {
        switch context {
        case .afterMeal: return afterMeal
        case .afterSitting: return afterSitting
        case .afterStress: return afterStress
        case .sleepDeprived: return sleepDeprived
        case .afterActivity: return afterActivity
        case .noSpecialCondition: return 0
        }
    }
}

struct LowBarrierExercise: Identifiable, Equatable, Sendable {
    let id: String
    let scene: ExerciseScene
    let name: String
    let type: ExerciseType
    /// Fixed, reviewed copy from the source workbook. It is not generated by GPT.
    let movementAdvice: String
    /// Fixed, reviewed copy from the source workbook. It is not generated by GPT.
    let intensityAdvice: String
    let systemImageName: String
    let assetImageName: String?
    let energyTier: ExerciseEnergyTier
    let contextScores: ExerciseContextScores
    let catalogOrder: Int

    var movementAdviceSteps: [String] {
        adviceLines(from: movementAdvice)
    }

    var intensityAdviceSteps: [String] {
        adviceLines(from: intensityAdvice)
    }

    func assetImageName(for presentationSex: ExercisePresentationSex) -> String? {
        guard let assetImageName else { return nil }
        return presentationSex == .male ? "\(assetImageName)Male" : assetImageName
    }

    private func adviceLines(from advice: String) -> [String] {
        advice
            .split(whereSeparator: \.isNewline)
            .map(String.init)
            .map { $0.trimmingCharacters(in: .whitespacesAndNewlines) }
            .filter { !$0.isEmpty }
    }
}

struct ExerciseRecommendation: Identifiable, Equatable, Sendable {
    var id: String { exercise.id }
    let exercise: LowBarrierExercise
    let score: Int
    let energyScore: Int
    let contextScore: Int
}

